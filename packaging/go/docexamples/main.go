// Command docexamples turns the Go blocks of a Markdown page into packages that `go vet` checks
// against the module: a block starting with `package main` is a program of its own; the others
// are function bodies returning an error, given the variables the page uses (ctx, client,
// privateKey, passphrase, resourceID, folderID, userID, groupID).
//
//	go run packaging/go/docexamples/main.go docs/sdk/go.md build/smoke/docs
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

var block = regexp.MustCompile("(?ms)^```go\n(.*?)^```")

const header = `// Generated by packaging/go/docexamples from %s.
package main

import (
	"context"
	"errors"
	"fmt"
	"log"
	"os"
	"time"

	passbolt "github.com/scadra/passbolt-sdk-go"
)

// Each body may leave a package aside.
var (
	_ = context.Background
	_ = errors.Is
	_ = fmt.Println
	_ = log.Fatal
	_ = os.Getenv
	_ = time.Second
	_ = passbolt.Call[int]
)

// The variables the page uses.
var (
	ctx    = context.Background()
	client *passbolt.PassboltClient

	privateKey, passphrase, resourceID, folderID, userID, groupID string
)

func main() {}
`

const function = `
// %s, line %d.
func example%d() error {
%s
	return nil
}
`

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: docexamples <page.md> <out dir>")
		os.Exit(2)
	}
	page, out := os.Args[1], os.Args[2]
	src, err := os.ReadFile(page)
	if err != nil {
		fail(err)
	}
	var snippets strings.Builder
	fmt.Fprintf(&snippets, header, filepath.Base(page))
	programs := 0
	matches := block.FindAllSubmatchIndex(src, -1)
	for i, m := range matches {
		code := string(src[m[2]:m[3]])
		line := 1 + strings.Count(string(src[:m[0]]), "\n")
		if strings.HasPrefix(code, "package main") {
			programs++
			write(filepath.Join(out, fmt.Sprintf("program%d", programs)), code)
			continue
		}
		fmt.Fprintf(&snippets, function, filepath.Base(page), line, i, code)
	}
	write(filepath.Join(out, "snippets"), snippets.String())
	fmt.Printf("docexamples: %d blocks of %s\n", len(matches), page)
}

func write(dir, code string) {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		fail(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "main.go"), []byte(code), 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "docexamples:", err)
	os.Exit(1)
}
